// 날짜 기준으로 골라 하루 동안 같은 문장 노출
export const getMockTodaySentence = (): TodaySentence => {
  const now = new Date();
  const days = Math.floor(now.getTime() / 86_400_000 - now.getTimezoneOffset() / 1440);

  return mockTodaySentences[days % mockTodaySentences.length];
};
